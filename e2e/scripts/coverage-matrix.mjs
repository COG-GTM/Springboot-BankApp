// Builds qa/coverage-matrix.md from the manual plan, the Playwright specs and (if present) results.json.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const e2e = join(root, 'e2e');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows.filter((r) => r.length > 1);
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

const plan = parseCsv(readFileSync(join(root, 'qa', 'manual-test-plan.csv'), 'utf8'));
const decisions = JSON.parse(readFileSync(join(root, 'qa', 'not-automated.json'), 'utf8'));

const tests = new Map();
for (const file of readdirSync(join(e2e, 'tests')).filter((f) => f.endsWith('.spec.ts'))) {
  for (const m of readFileSync(join(e2e, 'tests', file), 'utf8').matchAll(/test\('(MT-\d{3})[^']*'/g)) {
    tests.set(m[1], `e2e/tests/${file}`);
  }
}

const results = new Map();
const resultsPath = join(e2e, 'results.json');
if (existsSync(resultsPath)) {
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      const id = spec.title.match(/^MT-\d{3}/)?.[0];
      if (id) results.set(id, spec.tests.every((t) => t.status === 'expected') ? 'pass' : 'FAIL');
    }
    (suite.suites ?? []).forEach(walk);
  };
  JSON.parse(readFileSync(resultsPath, 'utf8')).suites.forEach(walk);
}

const label = { 'not-automatable': 'Not automatable', 'needs-clarification': 'Needs QA clarification' };
const counts = { automated: 0, 'not-automatable': 0, 'needs-clarification': 0, unmapped: 0 };
const lines = [];
for (const row of plan) {
  let status, where;
  if (tests.has(row.id)) {
    counts.automated++;
    status = 'Automated' + (results.has(row.id) ? ` (${results.get(row.id)})` : '');
    where = `\`${tests.get(row.id)}\``;
  } else if (decisions[row.id]) {
    counts[decisions[row.id].status]++;
    status = label[decisions[row.id].status];
    where = decisions[row.id].reason;
  } else {
    counts.unmapped++;
    status = 'UNMAPPED';
    where = 'No test and no recorded decision';
  }
  lines.push(`| ${row.id} | ${row.area} | ${row.title} | ${status} | ${where} |`);
}

const passed = [...results.values()].filter((r) => r === 'pass').length;
const out = [
  '# Coverage matrix: manual regression plan to Playwright',
  '',
  'Generated by `npm run matrix` in `e2e/` from `qa/manual-test-plan.csv`, `qa/not-automated.json` and the Playwright specs.',
  '',
  `- Manual cases: ${plan.length}`,
  `- Automated: ${counts.automated}` + (results.size ? ` (${passed} passing in the last run)` : ''),
  `- Not automatable: ${counts['not-automatable']}`,
  `- Needs QA clarification: ${counts['needs-clarification']}`,
  `- Unmapped: ${counts.unmapped}`,
  '',
  '| ID | Area | Manual case | Status | Automated test or reason |',
  '| --- | --- | --- | --- | --- |',
  ...lines,
  '',
].join('\n');

writeFileSync(join(root, 'qa', 'coverage-matrix.md'), out);
console.log(out.split('\n').slice(0, 10).join('\n'));
if (counts.unmapped) process.exit(1);
