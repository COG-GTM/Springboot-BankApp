#!/usr/bin/env node
// Builds qa/coverage-matrix.md from the manual plan, the Playwright specs and qa/not-automated.csv.
//   node scripts/coverage.mjs                    write qa/coverage-matrix.md
//   node scripts/coverage.mjs --check            fail if any row is unaccounted for or the matrix is stale
//   node scripts/coverage.mjs --results <json>   also print a matrix with CI results (for the job summary)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const e2eDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(e2eDir, '..');
const planPath = join(repoRoot, 'qa/manual-test-plan.csv');
const notAutomatedPath = join(repoRoot, 'qa/not-automated.csv');
const matrixPath = join(repoRoot, 'qa/coverage-matrix.md');
const testsDir = join(e2eDir, 'tests');

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));
}

function scanSpecs() {
  const found = new Map();
  for (const file of readdirSync(testsDir).filter((f) => f.endsWith('.spec.ts'))) {
    const src = readFileSync(join(testsDir, file), 'utf8');
    for (const m of src.matchAll(/\btest(?:\.\w+)?\(\s*['"`](MT-\d{3})\b([^'"`]*)['"`]/g)) {
      const list = found.get(m[1]) ?? [];
      list.push({ file: relative(repoRoot, join(testsDir, file)), title: `${m[1]}${m[2]}` });
      found.set(m[1], list);
    }
  }
  return found;
}

function readResults(path) {
  const byId = new Map();
  const walk = (suite) => {
    for (const s of suite.suites ?? []) walk(s);
    for (const spec of suite.specs ?? []) {
      const id = spec.title.match(/^MT-\d{3}/)?.[0];
      if (!id) continue;
      const statuses = spec.tests.flatMap((t) => t.results.map((r) => r.status));
      const ok = spec.ok && statuses.length > 0 && statuses.every((s) => s === 'passed');
      byId.set(id, ok ? 'passed' : statuses.includes('skipped') ? 'skipped' : 'failed');
    }
  };
  walk(JSON.parse(readFileSync(path, 'utf8')));
  return byId;
}

const cell = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function render(plan, specs, notAutomated, results) {
  const automated = plan.filter((r) => specs.has(r.id));
  const lines = [];
  lines.push('# Regression coverage matrix', '');
  lines.push('Generated by `e2e/scripts/coverage.mjs` from `qa/manual-test-plan.csv`, `e2e/tests/*.spec.ts` and `qa/not-automated.csv`. Do not edit by hand; run `npm run coverage` in `e2e/`.', '');
  lines.push(`**${plan.length} rows: ${automated.length} automated, ${plan.length - automated.length} not automated.**`, '');
  if (results) {
    const counts = { passed: 0, failed: 0, skipped: 0, 'not run': 0 };
    for (const r of automated) counts[results.get(r.id) ?? 'not run']++;
    lines.push(`CI result: ${counts.passed} passed, ${counts.failed} failed, ${counts.skipped} skipped, ${counts['not run']} not run.`, '');
  }
  lines.push('| Area | Automated | Not automated |', '|---|---|---|');
  for (const area of [...new Set(plan.map((r) => r.area))]) {
    const rows = plan.filter((r) => r.area === area);
    const a = rows.filter((r) => specs.has(r.id)).length;
    lines.push(`| ${area} | ${a} | ${rows.length - a} |`);
  }
  lines.push('', '## All rows', '');
  const head = ['ID', 'Area', 'Title', 'Priority', 'Status', 'Playwright test'];
  if (results) head.push('CI result');
  lines.push(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`);
  for (const r of plan) {
    const tests = specs.get(r.id);
    const status = tests ? 'Automated' : 'Not automated';
    const where = tests ? tests.map((t) => `\`${t.file}\``).join(', ') : 'see below';
    const row = [r.id, r.area, cell(r.title), r.priority, status, where];
    if (results) row.push(tests ? results.get(r.id) ?? 'not run' : 'n/a');
    lines.push(`| ${row.join(' | ')} |`);
  }
  lines.push('', '## Rows not automated', '');
  lines.push('| ID | Title | Expected (from plan) | Why not automated | Evidence |', '|---|---|---|---|---|');
  for (const r of plan.filter((p) => !specs.has(p.id))) {
    const na = notAutomated.get(r.id);
    lines.push(`| ${r.id} | ${cell(r.title)} | ${cell(r.expected)} | ${cell(na?.reason)} | ${cell(na?.evidence) || '-'} |`);
  }
  return lines.join('\n') + '\n';
}

const args = process.argv.slice(2);
const plan = parseCsv(readFileSync(planPath, 'utf8'));
const notAutomated = new Map(parseCsv(readFileSync(notAutomatedPath, 'utf8')).map((r) => [r.id, r]));
const specs = scanSpecs();
const planIds = new Set(plan.map((r) => r.id));

const errors = [];
if (plan.length !== planIds.size) errors.push('duplicate IDs in manual-test-plan.csv');
for (const r of plan) {
  const hasTest = specs.has(r.id);
  const listed = notAutomated.has(r.id);
  if (!hasTest && !listed) errors.push(`${r.id} has no Playwright test and is not in qa/not-automated.csv`);
  if (hasTest && listed) errors.push(`${r.id} has a Playwright test but is also listed in qa/not-automated.csv`);
  if (listed && !notAutomated.get(r.id).reason.trim()) errors.push(`${r.id} is not automated but has no reason`);
}
for (const id of specs.keys()) if (!planIds.has(id)) errors.push(`test references ${id}, which is not in the plan`);
for (const id of notAutomated.keys()) if (!planIds.has(id)) errors.push(`qa/not-automated.csv references ${id}, which is not in the plan`);

const resultsIdx = args.indexOf('--results');
let results;
if (resultsIdx !== -1) {
  const p = args[resultsIdx + 1];
  if (p && existsSync(p)) results = readResults(p);
  else errors.push(`results file not found: ${p}`);
}

if (errors.length) {
  console.error(`Coverage matrix check failed:\n- ${errors.join('\n- ')}`);
  process.exit(1);
}

const matrix = render(plan, specs, notAutomated, undefined);
if (args.includes('--check')) {
  const current = existsSync(matrixPath) ? readFileSync(matrixPath, 'utf8') : '';
  if (current !== matrix) {
    console.error('qa/coverage-matrix.md is out of date; run `npm run coverage` in e2e/ and commit the result.');
    process.exit(1);
  }
} else if (!results) {
  writeFileSync(matrixPath, matrix);
}
console.log(results ? render(plan, specs, notAutomated, results) : `All ${plan.length} rows accounted for (${[...planIds].filter((id) => specs.has(id)).length} automated).`);
